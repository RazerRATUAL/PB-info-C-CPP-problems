#include <fstream>
using namespace std;

ifstream cin("permutarecuvant.in");
ofstream cout("permutarecuvant.out");

int main()
{
    char sir[30];
    cin >> sir;
    int i = 0;
    while (sir[i] != '\0')
    {
        int j = i;
        while (sir[j] != '\0')
        {
            cout << sir[j];
            j++;
        }
        for (int k = 0; k < i; ++k)
            cout << sir[k];
        cout << ' ';
        i++;
    }
    return 0;
}
